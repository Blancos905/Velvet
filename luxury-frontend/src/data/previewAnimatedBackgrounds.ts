export function readStoredPreviewAnimatedBgIndex(): number | null {
  if (typeof sessionStorage === "undefined") return null;
  try {
    const raw = sessionStorage.getItem(PREVIEW_ANIMATED_BG_STORAGE_KEY);
    if (raw === null) return null;
    const n = Number.parseInt(raw, 10);
    if (!Number.isFinite(n) || n < 0 || n >= PREVIEW_ANIMATED_BG_COUNT) return null;
    return n;
  } catch {
    return null;
  }
}

export function writeStoredPreviewAnimatedBgIndex(index: number): void {
  try {
    sessionStorage.setItem(PREVIEW_ANIMATED_BG_STORAGE_KEY, String(index));
  } catch {
    /* ignore */
  }
}

