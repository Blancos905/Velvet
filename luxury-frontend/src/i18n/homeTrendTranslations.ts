export function localizedTrendText(
  locale: UiLocale,
  groupId: string,
  itemId: string,
  fallback: TrendText,
): TrendText {
  if (locale === "it") return fallback;
  const key = `${groupId}.${itemId}`;
  const pack = HOME_TREND_TRANSLATIONS[locale]?.[key] ?? HOME_TREND_TRANSLATIONS.en?.[key];
  return pack ?? fallback;
}

export function localizedTrendGroupHeading(locale: UiLocale, groupId: string, fallback: string): string {
  if (locale === "it") return fallback;
  return TREND_GROUP_HEADING[locale]?.[groupId] ?? TREND_GROUP_HEADING.en?.[groupId] ?? fallback;
}
