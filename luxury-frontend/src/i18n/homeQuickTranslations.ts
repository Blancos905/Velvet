export function localizeQuickSuggestGroups(locale: UiLocale, groups: QuickSuggestGroup[]): QuickSuggestGroup[] {
  if (locale === "it") return groups;
  const pack = PACKS[locale] ?? PACKS.en;
  if (!pack) return groups;
  return groups.map((g) => ({
    ...g,
    label: pack.groups[g.id] ?? g.label,
    tags: g.tags.map((tag) => ({
      ...tag,
      label: pack.tags[tag.q.trim().toLowerCase()] ?? tag.label,
    })),
  }));
}
